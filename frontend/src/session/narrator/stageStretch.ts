const FORMAT_CYCLE_LENGTH = 4;

function formatContinuePrompt(phrase: string, formatIndex: number): string {
  switch (formatIndex) {
    case 0:
      return phrase;
    case 1:
      return `Не повторяй уже сказанное, ${phrase}`;
    case 2:
      return `${phrase}, продолжай рассказывать историю дальше`;
    default:
      return `Не повторяй уже сказанное, ${phrase}, продолжай рассказывать историю дальше`;
  }
}

